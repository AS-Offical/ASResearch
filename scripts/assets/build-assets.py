#!/usr/bin/env python3
"""Phase 0 asset pipeline. Never modifies Resources/ (source of truth).

Outputs:
  public/fonts/pixel-ae/*.woff2      from Resources/fonts/Pixel-AE/*.ttf
  public/brand/*.svg                  derived logos (outlined, fill=currentColor)
  src/components/brand/logo-data.ts   generated path data for inline <svg>
Requires: fonttools, brotli. IBM Plex Mono (OFL) is only used to outline the
"Researches" <text> that the source SVGs still contain.
Usage: python3 -I scripts/assets/build-assets.py <plex-mono-latin-400.woff2>
"""
import json, os, re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "Resources")
plex = TTFont(sys.argv[1])
cmap, gs, upm = plex.getBestCmap(), plex.getGlyphSet(), plex["head"].unitsPerEm

# --- Pixel AE -> WOFF2 (glyph data untouched, no subsetting: keeps Arabic shaping intact)
out = os.path.join(ROOT, "public/fonts/pixel-ae"); os.makedirs(out, exist_ok=True)
for w in ("Regular", "Bold"):
    f = TTFont(os.path.join(RES, f"fonts/Pixel-AE/PixelAE-{w}.ttf")); f.flavor = "woff2"
    f.save(os.path.join(out, f"PixelAE-{w}.woff2"))

# --- Logos
def outline(text, size, tx, ty):
    s, x, parts = size / upm, 0, []
    for ch in text:
        g = cmap[ord(ch)]; pen = SVGPathPen(gs, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, tx + x * s, ty)))
        parts.append(pen.getCommands()); x += gs[g].width
    return " ".join(parts), x * s

data = {}
for name, src in (("as", "AS.svg"), ("as-researches", "AS Researches.svg"), ("researches", "Researches.svg")):
    svg = open(os.path.join(RES, "brand/logos", src), encoding="utf-8").read()
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    paths = re.findall(r'<path d="([^"]+)"', svg)
    t = re.search(r'<text transform="matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)"[^>]*class="cls-\d"><tspan[^>]*>([^<]+)</tspan>', svg)
    if t:
        size = float(re.search(r"font-size:([\d.]+)", svg).group(1))
        d, adv = outline(t.group(3), size, float(t.group(1)), float(t.group(2)))
        paths.append(d)
        print(f"{name}: outlined '{t.group(3)}' advance={adv:.3f} (source viewBox width {vb.split()[2]})")
    data[name] = {"viewBox": vb, "paths": paths}
    os.makedirs(os.path.join(ROOT, "public/brand"), exist_ok=True)
    body = "".join(f'<path d="{d}"/>' for d in paths)
    open(os.path.join(ROOT, f"public/brand/{name}.svg"), "w").write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" fill="currentColor">{body}</svg>\n')

os.makedirs(os.path.join(ROOT, "src/components/brand"), exist_ok=True)
with open(os.path.join(ROOT, "src/components/brand/logo-data.ts"), "w") as f:
    f.write("// GENERATED by scripts/assets/build-assets.py from Resources/brand/logos. Do not edit.\n")
    f.write("export const LOGOS = " + json.dumps(data, indent=2) + " as const;\n")
    f.write("export type LogoName = keyof typeof LOGOS;\n")
